namespace AuditSphereOps.Application.Accounting;

public static partial class NativeTrialBalanceSourceWorkspace
{
  private sealed record Retained(TrialBalanceDataset Dataset, NativeTrialBalanceSource Evidence, Manifest Manifest);

  private static async Task<CommandResult<Retained>> RetainedAsync(IClientAccountingDbContext db,
    TrialBalanceDataset source, CancellationToken ct)
  {
    var evidence = await db.NativeTrialBalanceSources.AsNoTracking().SingleOrDefaultAsync(x => x.DatasetId == source.Id &&
      x.FirmId == source.FirmId && x.ClientId == source.ClientId && x.EngagementId == source.EngagementId, ct);
    if (evidence is null) return Fail<Retained>(ErrorCodes.ProtectedState, "The native source has no exact retained evidence.");
    try
    {
      var m = JsonSerializer.Deserialize<Manifest>(evidence.ManifestJson);
      if (m is null || m.Pins is null || m.TrialBalance is null || m.TrialBalance.Rows is null ||
          m.TrialBalance.Rows.Any(x => x is null) || string.IsNullOrWhiteSpace(m.Pins.MembershipJson) || m.Version != Version || m.FirmId != source.FirmId || m.ClientId != source.ClientId ||
          m.EngagementId != source.EngagementId || m.PeriodId != source.PeriodId || m.Currency != source.Currency ||
          m.Basis != source.Basis || m.LegalEntityKey != source.LegalEntityKey || m.BookScope != BookScope ||
          source.BookId is not null || source.ImportBatchId is not null || source.RawFileSha256Hex != "" ||
          source.ImportProfileVersion != NativeProfile.Version || source.SourceLayout != NativeProfile.Layout ||
          source.ImportState != TrialBalanceImportStates.Sealed || evidence.ActorId != source.ImportedByUserId ||
          HashText(evidence.ManifestJson) != evidence.ManifestHash || HashText(evidence.GeneratedRowsJson) != evidence.GeneratedRowsHash ||
          evidence.GeneratedRowsHash != m.GeneratedRowsHash || Identity(m) != evidence.SourceIdentityHash || source.Sha256Hex != evidence.SourceIdentityHash ||
          m.RowsDigest != source.NormalizedDatasetDigest || m.TrialBalance.Rows.Count != evidence.RowCount ||
          evidence.RowCount is < 1 or > 250_000 || JsonSerializer.Serialize(m.TrialBalance.Rows) != evidence.GeneratedRowsJson ||
          m.AsOfDate < m.PeriodStart || m.AsOfDate > m.PeriodEnd || m.PeriodRevision < 1 ||
          m.ActivityOnly != (m.Pins.OpeningHash is null))
        return Fail<Retained>(ErrorCodes.ProtectedState, "The retained native source identity or generated bytes failed integrity checks.");
      var rows = await db.TrialBalanceRows.AsNoTracking().Where(x => x.DatasetId == source.Id)
        .OrderBy(x => x.AccountCode).Take(250_001).ToListAsync(ct);
      var generated = m.TrialBalance.Rows.OrderBy(x => x.AccountCode, StringComparer.Ordinal).ToArray();
      if (rows.Count != generated.Length || generated.Select(x => x.AccountCode).Distinct(StringComparer.Ordinal).Count() != generated.Length)
        return Fail<Retained>(ErrorCodes.ProtectedState, "Native source membership differs from the sealed manifest.");
      var byCode = rows.ToDictionary(x => x.AccountCode, StringComparer.Ordinal);
      foreach (var row in generated)
      {
        if (!byCode.TryGetValue(row.AccountCode, out var stored) || stored.AccountName != row.AccountName || stored.Entity != m.LegalEntityKey ||
            stored.Currency != m.Currency || stored.MappingCode is not null || stored.SourceDebit != Amount(row.ClosingDebit) ||
            stored.SourceCredit != Amount(row.ClosingCredit) || stored.Amount != Amount(row.ClosingDebit) - Amount(row.ClosingCredit) ||
            Amount(row.OpeningDebit) - Amount(row.OpeningCredit) + Amount(row.PeriodDebit) - Amount(row.PeriodCredit) != stored.Amount)
          return Fail<Retained>(ErrorCodes.ProtectedState, "The native accounting rows do not reproduce their retained source.");
      }
      var parsed = TrialBalanceCsvImporter.BuildParsed(rows.Select(x => new TbImportRow(x.AccountCode, x.AccountName,
        x.Amount, x.Currency, x.Entity, x.MappingCode, x.SourceDebit, x.SourceCredit)).ToArray(), m.Currency, "", NativeProfile);
      if (parsed.NormalizedDatasetDigest != source.NormalizedDatasetDigest || rows.Sum(x => x.Amount) != 0 ||
          generated.Sum(x => Amount(x.OpeningDebit)) != Amount(m.TrialBalance.OpeningDebit) ||
          generated.Sum(x => Amount(x.OpeningCredit)) != Amount(m.TrialBalance.OpeningCredit) ||
          generated.Sum(x => Amount(x.PeriodDebit)) != Amount(m.TrialBalance.PeriodDebit) ||
          generated.Sum(x => Amount(x.PeriodCredit)) != Amount(m.TrialBalance.PeriodCredit) ||
          generated.Sum(x => Amount(x.ClosingDebit)) != Amount(m.TrialBalance.ClosingDebit) ||
          generated.Sum(x => Amount(x.ClosingCredit)) != Amount(m.TrialBalance.ClosingCredit))
        return Fail<Retained>(ErrorCodes.ProtectedState, "Native row content or control totals no longer match the sealed manifest.");
      return CommandResult<Retained>.Ok(new(source, evidence, m));
    }
    catch (Exception ex) when (ex is JsonException or InvalidOperationException or FormatException or OverflowException or ArgumentException)
    { return Fail<Retained>(ErrorCodes.ProtectedState, "The native source manifest is malformed or unsupported."); }
  }

  internal static async Task<CommandResult> CheckIntegrityAsync(IAuditSphereDbContext db, TrialBalanceDataset source, CancellationToken ct)
  {
    if (source.SourceKind != SourceKind) return CommandResult.Ok();
    if (db is not IClientAccountingDbContext accounting)
      return CommandResult.Fail(ErrorCodes.GateBlocked, "Native source integrity requires the client accounting capability.");
    var retained = await RetainedAsync(accounting, source, ct);
    return retained.Succeeded ? CommandResult.Ok() : CommandResult.Fail(retained.ErrorCode!, retained.Message!);
  }

  /// <summary>Native-only source fence. Raw retains its existing workflow. Caller owns actor authorization.</summary>
  internal static async Task<CommandResult> CheckCurrentAsync(IAuditSphereDbContext db, TrialBalanceDataset source,
    CancellationToken ct = default, bool requireCoverage = true)
  {
    if (source.SourceKind != SourceKind) return CommandResult.Ok();
    if (db is not IClientAccountingDbContext accounting)
      return CommandResult.Fail(ErrorCodes.GateBlocked, "Native source verification requires the client accounting capability.");
    var retained = await RetainedAsync(accounting, source, ct);
    if (!retained.Succeeded) return CommandResult.Fail(retained.ErrorCode!, retained.Message!);
    var m = retained.Value!.Manifest;
    if (requireCoverage && (m.ActivityOnly || m.AsOfDate != m.PeriodEnd))
      return CommandResult.Fail(ErrorCodes.GateBlocked, "A complete reporting-period source requires its actual approved opening and period-end cutoff. Activity-only or interim evidence remains historical source evidence, not a complete reporting source.");
    var periodQuery = accounting.Database.CurrentTransaction is null
      ? accounting.ClientReportingPeriods.AsNoTracking().Where(x => x.FirmId == source.FirmId && x.ClientId == source.ClientId && x.Id == m.PeriodId)
      : accounting.ClientReportingPeriods.FromSqlInterpolated($"SELECT * FROM client_reporting_periods WHERE firm_id={source.FirmId} AND client_id={source.ClientId} AND id={m.PeriodId} FOR SHARE").AsNoTracking();
    var period = await periodQuery.SingleOrDefaultAsync(ct);
    if (period is null || period.StartDate != m.PeriodStart || period.EndDate != m.PeriodEnd ||
        period.Basis != m.Basis || period.Currency != m.Currency || !PeriodRevisionMatches(period, m.PeriodRevision))
      return CommandResult.Fail(ErrorCodes.StaleRevision, "The native source period was amended or reopened; its captured source must not be rebound.");
    var pins = await ReadPinsAsync(accounting, source.FirmId, source.ClientId, m.PeriodId, ct);
    return pins.Succeeded && pins.Value == m.Pins ? CommandResult.Ok() :
      CommandResult.Fail(pins.Succeeded ? ErrorCodes.StaleRevision : pins.ErrorCode!,
        pins.Succeeded ? "Native postings, opening, chart, profile or mandate changed. Capture and independently accept a successor source." : pins.Message!);
  }

  internal static async Task<CommandResult> CheckReportingAsync(IAuditSphereDbContext db, TrialBalanceDataset source,
    CancellationToken ct = default)
  {
    if (source.SourceKind != SourceKind) return CommandResult.Ok();
    var current = await CheckCurrentAsync(db, source, ct);
    if (!current.Succeeded) return current;
    if (source.ValidationStatus != "Accepted" || !source.Balanced || source.ControlTotal != 0m)
      return CommandResult.Fail(ErrorCodes.GateBlocked, "The native source must pass technical validation before reporting use.");
    var selected = await (from decision in db.SourceAcceptanceDecisions.AsNoTracking()
      join dataset in db.TrialBalanceDatasets.AsNoTracking() on decision.TrialBalanceDatasetId equals dataset.Id
      where decision.FirmId == source.FirmId && decision.ClientId == source.ClientId && decision.EngagementId == source.EngagementId &&
        decision.SourceKind == AccountingSourceKinds.TrialBalance && decision.Decision == "ACCEPTED" &&
        dataset.FirmId == source.FirmId && dataset.ClientId == source.ClientId && dataset.EngagementId == source.EngagementId &&
        dataset.PeriodId == source.PeriodId && dataset.BookId == source.BookId && dataset.Basis == source.Basis &&
        dataset.Currency == source.Currency && dataset.LegalEntityKey == source.LegalEntityKey
      orderby decision.CreatedAt descending, decision.Id descending
      select decision).FirstOrDefaultAsync(ct);
    return selected is not null && selected.TrialBalanceDatasetId == source.Id && selected.SourceIdentityHash == source.Sha256Hex &&
      selected.AcceptedByUserId != source.ImportedByUserId
      ? CommandResult.Ok() : CommandResult.Fail(ErrorCodes.GateBlocked, "Independently accept this exact current native source before mapping or package use.");
  }

  private static bool PeriodRevisionMatches(ClientReportingPeriod period, long captured) =>
    period.Revision == captured && period.Status is "ACTIVE" or "DRAFT" ||
    captured < long.MaxValue && period.Revision == captured + 1 && period.Status == AccountingWorkflowStates.Closed &&
      period.ClosedByUserId is not null && period.ClosedAt is not null && !string.IsNullOrWhiteSpace(period.CloseReason);

  public static async Task<CommandResult<NativeTrialBalanceSourceView>> ViewAsync(IClientAccountingDbContext db,
    ActorContext actor, Guid datasetId, CancellationToken ct = default)
  {
    var source = await db.TrialBalanceDatasets.AsNoTracking().SingleOrDefaultAsync(x => x.Id == datasetId &&
      x.FirmId == actor.FirmId && x.SourceKind == SourceKind && x.ImportState == TrialBalanceImportStates.Sealed, ct);
    if (source is null) return Fail<NativeTrialBalanceSourceView>(ErrorCodes.ScopeDenied, "Access denied.");
    var auth = await AuthorizeAsync(db, actor, source.ClientId, source.EngagementId, false, ct);
    if (!auth.Succeeded) return Fail<NativeTrialBalanceSourceView>(auth.ErrorCode!, auth.Message!);
    var retained = await RetainedAsync(db, source, ct);
    if (!retained.Succeeded) return Fail<NativeTrialBalanceSourceView>(retained.ErrorCode!, retained.Message!);
    var current = await CheckCurrentAsync(db, source, ct, requireCoverage: false);
    auth = await AuthorizeAsync(db, actor, source.ClientId, source.EngagementId, false, ct);
    if (!auth.Succeeded) return Fail<NativeTrialBalanceSourceView>(auth.ErrorCode!, auth.Message!);
    var r = retained.Value!;
    return CommandResult<NativeTrialBalanceSourceView>.Ok(new(source.Id, source.ClientId, source.EngagementId,
      r.Manifest.PeriodId, r.Manifest.AsOfDate.ToString("yyyy-MM-dd"), source.LegalEntityKey, BookScope, SourceKind,
      r.Manifest.ActivityOnly, r.Evidence.RowCount, r.Evidence.SourceIdentityHash, r.Evidence.ManifestHash,
      r.Evidence.GeneratedRowsHash, source.ValidationStatus, current.Succeeded, current.Succeeded ? null : current.Message,
      r.Evidence.ActorId, r.Evidence.CreatedAt));
  }

  public static async Task<CommandResult<NativeTrialBalanceSourceArtifact>> ArtifactAsync(IClientAccountingDbContext db,
    ActorContext actor, Guid datasetId, CancellationToken ct = default)
  {
    var view = await ViewAsync(db, actor, datasetId, ct);
    if (!view.Succeeded) return Fail<NativeTrialBalanceSourceArtifact>(view.ErrorCode!, view.Message!);
    var evidence = await db.NativeTrialBalanceSources.AsNoTracking().SingleAsync(x => x.DatasetId == datasetId && x.FirmId == actor.FirmId, ct);
    var final = await ViewAsync(db, actor, datasetId, ct);
    if (!final.Succeeded) return Fail<NativeTrialBalanceSourceArtifact>(final.ErrorCode!, final.Message!);
    return CommandResult<NativeTrialBalanceSourceArtifact>.Ok(new(datasetId, $"auditsphere-native-tb-{datasetId:D}.json",
      "application/json", evidence.GeneratedRowsJson, evidence.GeneratedRowsHash, evidence.ManifestJson,
      evidence.ManifestHash, evidence.SourceIdentityHash, final.Value!.IsCurrent, final.Value.CurrentnessBlocker));
  }
}
