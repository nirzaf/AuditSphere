"""Generate architecture_and_requirements.openui from architecture_and_requirements.html.

Uses only the OpenUI default component library (Stack, Tabs/TabItem, Table/Col,
Steps, CodeBlock, Callout, MarkDownRenderer, charts, ...) so the file renders in
any stock OpenUI <Renderer />. Every value is read from the source HTML; nothing
is invented.

Usage: python3 scratchpad/build_openui.py [source.html] [output.openui]
"""
import json
import sys
from collections import Counter

from bs4 import BeautifulSoup

SRC = sys.argv[1] if len(sys.argv) > 1 else "architecture_and_requirements.html"
OUT = sys.argv[2] if len(sys.argv) > 2 else "architecture_and_requirements.openui"

with open(SRC, encoding="utf-8") as f:
    soup = BeautifulSoup(f.read(), "html.parser")

data = json.loads(soup.find("script", type="application/json").string)
diagrams = data["diagrams"]
titles = data["titles"]
search = data["search"]
snapshot = data["snapshot"]


def text(el):
    return el.get_text(" ", strip=True) if el else ""


def s(value):
    """OpenUI string literal: double quotes, backslash escapes, single line."""
    return json.dumps(value, ensure_ascii=False)


def by_kind(kind):
    return [i for i in search if i["kind"] == kind]


def table_rows(table):
    rows = table.find_all("tr")
    head = [text(c) for c in rows[0].find_all(["th", "td"])]
    body = [[text(c) for c in r.find_all(["th", "td"])] for r in rows[1:]]
    return head, [r for r in body if len(r) == len(head)]


lines = []


def emit(name, expr):
    assert "\n" not in expr, name
    lines.append(f"{name} = {expr}")


def arr(items):
    return "[" + ", ".join(items) + "]"


def table(name, head, rows):
    """Table is column-oriented: Table([Col(label, values), ...])."""
    cols = [f"Col({s(h)}, {arr(s(r[i]) for r in rows)})" for i, h in enumerate(head)]
    emit(name, f"Table({arr(cols)})")


# ---------- source extraction ----------
diagram_ids = [f"diagram-{i:02d}" for i in range(16)]
views = []
for did in diagram_ids:
    sec = soup.find("section", id=did)
    views.append({
        "id": did,
        "n": did[-2:],
        "title": titles[did],
        "lead": text(sec.find("p", class_="lead")) if sec else "",
        "mermaid": diagrams[did].replace("\r\n", "\n"),
    })

reqs = by_kind("Historical requirement")
req_sec = soup.find("section", id="requirements")
module_names = [text(h) for h in req_sec.find_all("h2")]
assert len(module_names) == 5, module_names
modules = {f"M{i + 1}": name for i, name in enumerate(module_names)}
req_counts = Counter(r["id"].split(".")[0] for r in reqs)
assert set(req_counts) == set(modules), req_counts

ctrl_head, ctrl_rows = table_rows(soup.find("section", id="controls").find("table"))
personas = []
for card in soup.find("section", id="controls").select("article[id^=persona-]"):
    personas.append((text(card.find(class_="eyebrow")), text(card.find("h3")),
                     [text(li) for li in card.find_all("li")]))

lc_head, lc_rows = table_rows(soup.find("section", id="lifecycle").find("table"))

ext_items = by_kind("Supplied extension — unverified")
ext_tables = soup.find("section", id="extensions").find_all("table")
ext_meta = []
for t in ext_tables:
    kv = {text(r.find_all(["th", "td"])[0]): text(r.find_all(["th", "td"])[-1]) for r in t.find_all("tr")}
    ext_meta.append(kv)

current = {i["id"]: i for i in by_kind("Current v2.2 source excerpt")}
cur_sec = soup.find("section", id="current")
dualkey_head, dualkey_rows = table_rows(cur_sec.find_all("table")[0])
phase_head, phase_rows = table_rows(cur_sec.find_all("table")[1])

findings = by_kind("Prior review finding")
review_sec = soup.find("section", id="review")
check_head, check_rows = table_rows(review_sec.find_all("table")[1])
severity = Counter("High" if "— High:" in f["title"] else "Medium" for f in findings)

overview = soup.find("section", id="overview")
overview_paras = [text(p) for p in overview.find_all("p")][:3] if overview else []

counts = Counter(i["kind"] for i in search)

# ---------- OpenUI Lang (top-down: shell first, data last) ----------
lines.append("// AuditSphereOps — Architecture & Requirements Atlas (OpenUI Lang, default component library)")
lines.append(f"// Generated by scratchpad/build_openui.py from {SRC} · snapshot {snapshot[:12]}")

emit("root", "Stack([header, kpis, tabs], \"column\", \"l\")")
emit("header", "CardHeader(\"AuditSphere Architecture & Requirements Atlas\", "
     + s(f"16 architecture views · {counts['Historical requirement']} historical requirements · "
         f"{counts['Historical control']} controls · {counts['Historical lifecycle']} lifecycle stages · "
         f"{counts['Supplied extension — unverified']} extensions · snapshot {snapshot[:12]}") + ")")
emit("kpis", "Stack([kpiViews, kpiReqs, kpiCtrls, kpiStages, kpiExts, kpiFindings], \"row\", \"s\", \"start\", \"start\", true)")
for name, label, n, variant in [
    ("kpiViews", "Views", len(views), "info"),
    ("kpiReqs", "Requirements", len(reqs), "neutral"),
    ("kpiCtrls", "Controls", len(ctrl_rows), "neutral"),
    ("kpiStages", "Lifecycle stages", len(lc_rows), "neutral"),
    ("kpiExts", "Extensions (unverified)", len(ext_items), "warning"),
    ("kpiFindings", "Review findings", len(findings), "danger"),
]:
    emit(name, f"Tag({s(f'{n} {label}')}, null, \"lg\", {s(variant)})")

tabs = [("overview", "Overview"), ("diagrams", "Architecture views"), ("requirements", "Requirements"),
        ("current", "v2.2 decisions"), ("controls", "Controls & personas"), ("lifecycle", "Lifecycle"),
        ("extensions", "Extensions"), ("review", "Review findings")]
emit("tabs", f"Tabs({arr('tab_' + k for k, _ in tabs)})")
for k, label in tabs:
    emit(f"tab_{k}", f"TabItem({s(k)}, {s(label)}, {k}Content)")

# Overview
emit("overviewContent", arr(["ovIntro"] + [f"ovPara{i}" for i in range(len(overview_paras))]
                             + ["ovBoundary", "ovMix", "ovModules", "ovCatalog"]))
emit("ovIntro", "TextContent(\"One reference with every view connected: architecture atlas, historical requirements, "
     "supplied extensions, controls and operative v2.2 decision overlays.\", \"large\")")
for i, p in enumerate(overview_paras):
    emit(f"ovPara{i}", f"TextContent({s(p)})")
emit("ovBoundary", "Callout(\"warning\", \"Design is not production acceptance\", "
     "\"Historical statements are kept for provenance. Supplied extensions are unverified, and the prior review "
     "findings below still apply.\")")
emit("ovMix", f"PieChart({arr(s(k) for k in counts)}, {arr(str(v) for v in counts.values())}, \"donut\")")
emit("ovModules", f"HorizontalBarChart({arr(s(f'{m} · {n}') for m, n in modules.items())}, "
     f"[Series(\"Historical requirements\", {arr(str(req_counts[m]) for m in modules)})], \"grouped\", \"Requirements\", \"Module\")")
table("ovCatalog", ["#", "View", "Scope"], [[v["n"], v["title"], v["lead"]] for v in views])

# Architecture views: one header + Mermaid block per view
dg = []
for v in views:
    dg += [f"dgHead{v['n']}", f"dgCode{v['n']}"]
emit("diagramsContent", arr(["dgNote"] + dg))
emit("dgNote", "TextContent(\"Each view is Mermaid source; renderers with a Mermaid-aware CodeBlock draw it, others show the source.\", \"small\")")
for v in views:
    emit(f"dgHead{v['n']}", f"CardHeader({s(v['n'] + ' · ' + v['title'])}, {s(v['lead'])})")
    emit(f"dgCode{v['n']}", f"CodeBlock(\"mermaid\", {s(v['mermaid'])})")

# Requirements: one searchable table, filtered by module and free text
emit("$reqModule", "\"\"")
emit("$reqSearch", "\"\"")
emit("requirementsContent", "[rqNote, rqFilters, rqCount, rqTable]")
emit("rqNote", "Callout(\"info\", \"Historical baseline\", \"These statements are preserved for provenance. "
     "Where an approved v2.2 decision overlay differs, the overlay governs.\")")
emit("rqFilters", "Form(\"reqFilters\", rqButtons, [rqModuleField, rqSearchField])")
emit("rqButtons", "Buttons([Button(\"Clear filters\", @Reset($reqModule, $reqSearch), \"secondary\")])")
module_items = ['SelectItem("", "All modules")']
for m, name in modules.items():
    module_items.append(f"SelectItem({s(m)}, {s(f'{m} · {name} ({req_counts[m]})')})")
emit("rqModuleField", f"FormControl(\"Module\", Select(\"module\", {arr(module_items)}, \"All modules\", null, $reqModule))")
emit("rqSearchField", "FormControl(\"Search\", Input(\"search\", \"ID, feature or statement text\", \"text\", null, $reqSearch))")
emit("rqCount", "TextContent(\"\" + @Count(rqRows) + \" of " + str(len(reqs)) + " statements\", \"small-heavy\")")
emit("rqRows", "@Filter(rqByModule, \"haystack\", \"contains\", $reqSearch)")
emit("rqByModule", "@Filter(reqData, \"module\", \"contains\", $reqModule)")
emit("rqTable", "Table([Col(\"ID\", rqRows.id), Col(\"Module\", rqRows.moduleName), Col(\"Feature\", rqRows.feature), Col(\"Statement\", rqRows.text)])")
req_records = []
for r in reqs:
    m = r["id"].split(".")[0]
    feature = r["title"].split(" · ", 1)[-1]
    rec = {"id": r["id"], "module": m, "moduleName": modules[m], "feature": feature, "text": r["text"],
           "haystack": f"{r['id']} {feature} {r['text']}"}
    req_records.append("{" + ", ".join(f"{k}: {s(v)}" for k, v in rec.items()) + "}")
emit("reqData", arr(req_records))

# v2.2 decisions
emit("currentContent", "[cuDecHead, cuDecisions, cuKeyHead, cuKeyTable, cuKeyFlow, cuKeyText, "
     "cuPhaseHead, cuPhaseTable, cuTaskFlow, cuWorkflowText]")
emit("cuDecHead", f"CardHeader({s(current['current-decisions']['title'])}, \"Operative overlays on the historical baseline\")")
emit("cuDecisions", f"MarkDownRenderer({s(current['current-decisions']['text'])}, \"sunk\")")
emit("cuKeyHead", f"CardHeader({s(current['current-dual-key']['title'])}, \"Both keys must be present before an Engagement Letter\")")
table("cuKeyTable", dualkey_head, dualkey_rows)
emit("cuKeyFlow", f"CodeBlock(\"mermaid\", {s(diagrams['current-dual-key-0'])})")
emit("cuKeyText", f"MarkDownRenderer({s(current['current-dual-key']['text'])}, \"sunk\")")
emit("cuPhaseHead", f"CardHeader({s(current['current-workflow']['title'])}, \"Seven display phases projected from eleven canonical states\")")
table("cuPhaseTable", phase_head, phase_rows)
emit("cuTaskFlow", f"CodeBlock(\"mermaid\", {s(diagrams['current-workflow-addendum-0'])})")
emit("cuWorkflowText", f"MarkDownRenderer({s(current['current-workflow']['text'])}, \"sunk\")")

# Controls & personas
emit("controlsContent", arr(["ctHead", "ctTable", "psHead"] + [f"ps{i}" for i in range(len(personas))]))
emit("ctHead", "CardHeader(\"Controls and decision ownership\", \"Historical controls with their source enforcement labels\")")
table("ctTable", ctrl_head, ctrl_rows)
emit("psHead", "CardHeader(\"Original user personas\", \"Responsibilities as written in the source\")")
for i, (role, title, duties) in enumerate(personas):
    md = f"**{role} — {title}**\n\n" + "\n".join(f"- {d}" for d in duties)
    emit(f"ps{i}", f"MarkDownRenderer({s(md)}, \"card\")")

# Lifecycle
emit("lifecycleContent", "[lcHead, lcSteps, lcTable]")
emit("lcHead", "CardHeader(\"Eleven-state source register\", \"Derived lifecycle projection; no manually mutable stage column\")")
emit("lcSteps", f"Steps({arr(f'lcStep{i:02d}' for i in range(len(lc_rows)))})")
for i, r in enumerate(lc_rows):
    emit(f"lcStep{i:02d}", f"StepsItem({s(f'{i + 1:02d} · {r[0]}')}, {s(f'{r[1]}. Advance when: {r[2]} → {r[3]}')})")
table("lcTable", lc_head, lc_rows)

# Extensions
emit("extensionsContent", "[exNote, exTable, exSrcHead, exSrcTable]")
emit("exNote", "Callout(\"warning\", \"Supplied extensions are unverified\", "
     "\"Entries are shown as supplied; their enforcement references were not confirmed against the repository.\")")
table("exTable", ["ID", "Area", "Requirement"],
      [[e["id"], e["title"].split(" · ", 1)[-1], e["text"]] for e in ext_items])
emit("exSrcHead", "CardHeader(\"Supplied source mappings\", \"Citation, authority label and code alignment per supplied module\")")
meta_keys = list(dict.fromkeys(k for kv in ext_meta for k in kv))
table("exSrcTable", meta_keys, [[kv.get(k, "") for k in meta_keys] for kv in ext_meta])

# Review findings
emit("reviewContent", arr(["rvSeverity", "rvChecksHead", "rvChecks"] + [f"rv{i:02d}" for i in range(len(findings))]))
emit("rvSeverity", f"SingleStackedBarChart({arr(s(f'{k} severity') for k in severity)}, {arr(str(v) for v in severity.values())})")
emit("rvChecksHead", "CardHeader(\"Executed document checks\", \"What the prior review verified and its boundary\")")
table("rvChecks", check_head, check_rows)
for i, f in enumerate(findings):
    emit(f"rv{i:02d}", f"MarkDownRenderer({s(f['text'])}, \"card\")")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"Wrote {len(lines)} statements ({sum(map(len, lines)):,} chars) to {OUT}")
